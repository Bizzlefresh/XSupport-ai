"""Build docs/results.md (and data/evaluation/results_tables.csv) from the saved evaluation reports.

Every number comes from a JSON report in data/evaluation/; nothing is typed in by hand. Re-run after any evaluation script.
    python scripts/build_results.py            # write files
    python scripts/build_results.py --check    # exit 1 if the committed files differ from a fresh build
"""
import argparse
import csv
import io
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EV = ROOT / "data" / "evaluation"
OUT_MD = ROOT / "docs" / "results.md"
OUT_CSV = EV / "results_tables.csv"
M = {"lexical": "Keyword (TF-IDF)", "semantic": "Semantic", "hybrid": "Hybrid"}
NAMES = {"majority_baseline": "Majority class (floor)", "tfidf_logreg": "TF-IDF + logistic regression (deployed)", "tfidf_svm": "TF-IDF + linear SVM"}


def pct(x, d=1):
    return "n/a" if x is None else f"{x * 100:.{d}f}%"


def ci(v):
    return f"{v[0]:.2f} to {v[1]:.2f}"


def table(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def build() -> tuple[str, str]:
    cl = json.load(open(EV / "classification_report.json"))
    rt = json.load(open(EV / "retrieval_report.json"))
    asst = json.load(open(EV / "assistant_report.json"))
    inc = json.load(open(EV / "incident_report.json"))
    csv_rows: list[list] = [["section", "item", "metric", "value"]]
    md: list[str] = []
    w = md.append

    w("# Results\n")
    w("*Generated by `scripts/build_results.py` from the JSON reports in `data/evaluation/`. Do not edit by hand.*\n")
    w("**Read this first.** Every figure below comes from synthetic tickets written by this project's own generator, "
      "and the knowledge articles and their relevance labels were written by the same author (an AI assistant) and have not been "
      "reviewed by a person. These results show that the pipelines work and how they compare with each other on this data. "
      "They do **not** establish accuracy, time savings or usefulness on real helpdesk tickets.\n")

    # ---- classification
    sz = cl["dataset"]["sizes"]
    w("## 1. Ticket category classification\n")
    w(f"Dataset: {sum(sz.values())} synthetic tickets (seed {cl['dataset']['generator_seed']}, sha256 `{cl['dataset']['sha256'][:12]}`). "
      f"Primary split (new wording of known problems): train {sz['train']}, validation {sz['validation']}, test {sz['test']}. "
      "Model and settings were chosen on validation only; the test set was scored once.\n")
    rows = []
    for k in ("majority_baseline", "tfidf_logreg", "tfidf_svm"):
        t = cl["models"][k]["test"]
        s = cl["models"][k]["stress_novel_problem_types_test"]
        b = cl["test_uncertainty_bootstrap"][k]
        rows.append([NAMES[k], pct(t["accuracy"]), ci(b["accuracy_95ci"]), f"{t['macro_f1']:.3f}", ci(b["macro_f1_95ci"]), pct(s["accuracy"])])
        csv_rows += [["classification", k, "test_accuracy", t["accuracy"]], ["classification", k, "test_macro_f1", t["macro_f1"]],
                     ["classification", k, "stress_accuracy", s["accuracy"]]]
    w(table(["Model", "Test accuracy", "95% interval", "Macro-F1", "95% interval", "Accuracy on unseen problem types"], rows) + "\n")
    d = cl["test_uncertainty_bootstrap"]["paired_accuracy_difference"]
    w(f"Logistic regression minus SVM, paired difference in accuracy: {d['mean']:+.3f} (95% interval {ci(d['95ci'])}). {d['interpretation'].capitalize()}.\n")
    dm = cl["deployed"]["name"]
    th = cl["models"][dm]["threshold_test"]
    w(f"**Confidence threshold ({cl['deployed']['confidence_threshold']}, chosen on validation).** On test, the deployed model auto-suggests for "
      f"{pct(th['coverage'])} of tickets, correct {pct(th['accuracy_when_confident'])} of those times; {th['sent_to_manual_review']} tickets are flagged for "
      f"manual review, which catches {th['errors_caught_by_threshold']} of its {th['total_errors']} errors. Calibration error (ECE) "
      f"{cl['models'][dm]['calibration_test']['ece']:.3f}. Latency about {cl['latency']['mean_ms']} ms per ticket.\n")
    csv_rows += [["classification", dm, "coverage_at_threshold", th["coverage"]], ["classification", dm, "accuracy_when_confident", th["accuracy_when_confident"]]]

    # ---- retrieval
    w("## 2. Retrieval: similar incidents and knowledge articles\n")
    w(f"Semantic scorer: **{rt['embedding']['used']}**" + (" (a local latent-semantic stand-in; the pretrained sentence-embedding model could not be downloaded in the build environment and was never run)." if rt["embedding"]["used"] == "lsa" else ".") + "\n")
    for key, title, cap in (("similar_incidents", "Similar incidents", f"{rt['protocol']['ticket_queries']} against {rt['protocol']['ticket_corpus']}; a result is correct only if it is from the same scenario"),
                            ("articles", "Knowledge articles", f"{rt['protocol']['article_queries']} against {rt['protocol']['article_corpus']}; labels written by the project author")):
        w(f"**{title}** ({cap}).\n")
        rows = []
        for m in ("lexical", "semantic", "hybrid"):
            r = rt[key][m]
            rows.append([M[m], f"{r['precision_at_1']:.3f}", f"{r['recall_at_3']:.3f}", f"{r['recall_at_5']:.3f}", f"{r['mrr']:.3f} ({ci(r['mrr_ci95'])})", f"{r['ndcg_at_5']:.3f}"])
            for met in ("precision_at_1", "recall_at_5", "mrr", "ndcg_at_5"):
                csv_rows.append(["retrieval_" + key, m, met, r[met]])
        w(table(["Method", "Precision@1", "Recall@3", "Recall@5", "MRR (95% interval)", "nDCG@5"], rows) + "\n")
    w("Intervals overlap between methods, so no method is shown to be better than another. The article numbers are likely optimistic because the same author wrote articles and labels.\n")
    g = rt["article_threshold_on_test"]["hybrid"]
    w(f"**Weak-match threshold for articles (hybrid, {g['threshold']}).** Answers {pct(g['labelled_coverage'])} of tickets that have a matching article "
      f"({pct(g['labelled_answer_precision'])} correct) but still suggests an article for {g['unlabelled_queries_wrongly_answered']} of "
      f"{g['unlabelled_queries']} tickets that have none. No similarity threshold reached 80% precision for similar incidents.\n")

    # ---- assistant
    a = asst["results"]
    w("## 3. Troubleshooting assistant\n")
    w(f"{asst['protocol']['queries']} test tickets ({asst['protocol']['with_matching_article']} with a matching article, {asst['protocol']['without_matching_article']} without). "
      f"The assistant copies cited steps from approved articles and declines when the best article is below the validated threshold.\n")
    w(table(["Measure", "Value"], [
        ["Right call (correct cited steps, or declined when no article exists)", f"{pct(a['safe_outcome_rate'])} (95% interval {pct(a['safe_outcome_ci95'][0])} to {pct(a['safe_outcome_ci95'][1])})"],
        ["Offered steps when a matching article exists", pct(a["answered_when_article_exists"])],
        ["Top article correct when it offered steps", pct(a["correct_when_answered"])],
        ["Wrongly declined when an article exists", a["wrongly_declined_when_article_exists"]],
        ["Declined when no article exists", f"{a['declined_when_no_article']} of {a['no_article_queries']}"],
        ["Past resolution from the same scenario", pct(a["past_resolution_from_same_scenario"])]]) + "\n")
    w("This measures choosing and citing the right article. It does not measure whether following the steps resolves a ticket.\n")
    csv_rows += [["assistant", "hybrid", k, a[k]] for k in ("safe_outcome_rate", "answered_when_article_exists", "correct_when_answered")]

    # ---- incidents
    m_, o = inc["main_dataset"], inc["other_seeds"]
    w("## 4. Incident-burst detection\n")
    w(f"Rule: {inc['rule']}. On the main dataset it found {m_['truth_found']} of {m_['truth_bursts']} generator-planted bursts with {m_['false_alarms']} false alarms "
      f"(ticket recall {pct(m_['ticket_recall'])}, precision {pct(m_['ticket_precision'])}). Across {o['datasets']} other generator seeds it found {o['bursts_found']} of "
      f"{o['bursts_present']} bursts with {o['false_alarms']} false alarms. The planted bursts are tight one-morning clusters, so this is an easy test.\n")
    csv_rows += [["incidents", "main", "truth_found", m_["truth_found"]], ["incidents", "other_seeds", "false_alarms", o["false_alarms"]]]

    # ---- ai vs manual
    w("## 5. Where AI helps, and where a person is still needed (measured)\n")
    th = cl["models"][dm]["threshold_test"]
    w(table(["Task", "What the AI does", "What a person still does", "Measured evidence"], [
        ["Category", "Suggests a category with a confidence", f"Reviews and approves; all tickets below the threshold ({th['sent_to_manual_review']} of {cl['models'][dm]['test']['n']} on test)", f"Confident suggestions correct {pct(th['accuracy_when_confident'])} on {pct(th['coverage'])} of tickets; accuracy {pct(cl['models'][dm]['test']['accuracy'])} overall, {pct(cl['models'][dm]['stress_novel_problem_types_test']['accuracy'])} on unseen problem types"],
        ["Related articles", "Ranks approved articles", "Decides whether an article fits; writes and approves articles", f"Recall@5 {rt['articles']['hybrid']['recall_at_5']:.2f} (author-labelled, likely optimistic)"],
        ["Troubleshooting", "Shows cited steps, or says evidence is insufficient", "Follows or ignores the steps; resolves the ticket", f"Right call {pct(a['safe_outcome_rate'])}; effect on resolution not measured"],
        ["Incident spotting", "Flags bursts of tickets in one category", "Confirms and declares an incident", f"{m_['truth_found']} of {m_['truth_bursts']} planted bursts found, {m_['false_alarms']} false alarms"]]) + "\n")
    w("Live acceptance, correction and rating figures from technicians appear on the AI evaluation page and are not in this file, because they depend on the database in use.\n")

    # ---- not measured
    w("## 6. What has not been measured\n")
    for x in ("Accuracy on real tickets (no real data is used).", "Time saved per ticket or change in resolution time.",
              "Whether technicians find the suggestions useful (needs a study with real users; ratings are collected for this).",
              "The pretrained sentence-embedding model and a sentence-embedding classifier (the model could not be downloaded in the build environment).",
              "Fairness, long-term drift, or behaviour under unusual ticket text.", "Any benefit claim such as cost savings: these are hypotheses until measured."):
        w(f"- {x}")
    w("")
    w("## 7. Reproducing these numbers\n")
    w("```bash\npython scripts/train_classifier.py\npython scripts/evaluate_retrieval.py\npython scripts/evaluate_assistant.py\n"
      "python scripts/evaluate_incidents.py\npython scripts/build_results.py\n```\n")
    w("Latency figures vary between runs and machines; all other figures are reproducible and checked by the test suite.\n")

    buf = io.StringIO()
    csv.writer(buf, lineterminator="\n").writerows(csv_rows)
    return "\n".join(md), buf.getvalue()


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    md, cs = build()
    if a.check:
        ok = OUT_MD.exists() and OUT_MD.read_text() == md and OUT_CSV.exists() and OUT_CSV.read_text() == cs
        print("results up to date" if ok else "results.md / results_tables.csv are out of date: run scripts/build_results.py")
        sys.exit(0 if ok else 1)
    OUT_MD.write_text(md)
    OUT_CSV.write_text(cs)
    print(f"wrote {OUT_MD} and {OUT_CSV}")
